/// حالات تشغيل المقطع الصوتي (Audio Playback States)
/// تُستخدم للتعبير عن دورة حياة التشغيل بدقة داخل الـ Cubit والواجهات
enum PlaybackStatus {
  initial, // الحالة الابتدائية قبل تحميل أي مقطع
  loading, // جاري التحميل والتهيئة (Buffering)
  playing, // المقطع قيد التشغيل الفعلي
  paused, // تم الإيقاف المؤقت
  completed, // انتهى تشغيل المقطع الحالي
  error, // حدث خطأ أثناء تشغيل الملف الصوتي
}

